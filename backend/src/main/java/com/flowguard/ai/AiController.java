package com.flowguard.ai;

import com.flowguard.ai.dto.AiChatRequestDto;
import com.flowguard.ai.dto.AiChatResponseDto;
import com.flowguard.ai.dto.AiRootCauseResponseDto;
import com.flowguard.common.ApiResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.UUID;

@RestController
@RequestMapping("/api/v1/ai")
@RequiredArgsConstructor
@Tag(name = "AI Observability & Root Cause Analysis", description = "AI-powered incident RCA diagnosis, multi-signal telemetry synthesis, and natural language monitoring assistant")
public class AiController {

    private final AiAnalysisService aiService;

    @PostMapping("/incidents/{incidentId}/analysis")
    @PreAuthorize("hasAnyRole('SUPER_ADMIN', 'ADMIN', 'ENGINEER')")
    @Operation(summary = "Generate AI Root Cause Analysis (RCA) with confidence score, evidence citations, and remediation steps")
    public ResponseEntity<ApiResponse<AiRootCauseResponseDto>> analyzeIncident(@PathVariable UUID incidentId) {
        AiRootCauseResponseDto analysis = aiService.analyzeIncident(incidentId);
        return ResponseEntity.ok(ApiResponse.ok("Root cause analysis generated", analysis));
    }

    @PostMapping("/assistant/chat")
    @Operation(summary = "Ask the FlowGuard AI Monitoring Copilot natural language questions about telemetry, incidents, or latencies")
    public ResponseEntity<ApiResponse<AiChatResponseDto>> chatWithCopilot(@Valid @RequestBody AiChatRequestDto request) {
        AiChatResponseDto response = aiService.chatWithCopilot(request);
        return ResponseEntity.ok(ApiResponse.ok("Response generated by Copilot", response));
    }
}

